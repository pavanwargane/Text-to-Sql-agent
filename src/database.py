import sqlite3

def create_database():

    with sqlite3.connect("company.db") as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS employees (
                id INTEGER PRIMARY KEY,
                name TEXT,
                department TEXT,
                salary INTEGER
            )
            """
        )
        count=connection.execute("SELECT COUNT(*) FROM employees"
        ).fetchone()[0]
        if count == 0:
            connection.executemany(
                "INSERT INTO employees VALUES (?, ?, ?, ?)",
                [
                    (1, "Amit", "IT", 50000),
                    (2, "Priya", "HR", 40000),
                    (3, "Rahul", "IT", 60000),
                ],
            )
def get_schema():
    return """
             Table: employees
             Columns: id, name, department, salary"""

def run_sql(sql):
    with sqlite3.connect("file:company.db?mode=ro", uri=True) as connection:
        connection.execute("PRAGMA query_only =ON")

        ##executing query generated by ai
        cursor= connection.execute(sql)

        # Get the column names for the returned rows.
        columns = [column[0] for column in cursor.description]
         # Return the results as a list of dictionaries.
        return [
            dict(zip(columns, row))
            for row in cursor.fetchmany(100)
        ]